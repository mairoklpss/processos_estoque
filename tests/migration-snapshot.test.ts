import assert from 'node:assert/strict';
import test from 'node:test';
import fs from 'node:fs/promises';
import type { PoolClient } from 'pg';
import { createDatabase, seedDatabaseIfEmpty } from '../server/db.ts';
import { inspectSnapshot, migrationTables, verifyTarget } from '../server/migration-snapshot.ts';
import { localMigrationUrl } from '../server/postgres-migration.ts';

test('Migração: preflight íntegro, fingerprints e comparador detectam alteração de estoque', async () => {
  const db = createDatabase(':memory:'); seedDatabaseIfEmpty(db);
  try {
    const expected = inspectSnapshot(db);
    assert.equal(expected.find(t => t.table === 'usuarios')!.count, 2);
    assert.equal(expected.find(t => t.table === 'itens')!.count, 6);
    assert.ok(!expected.some(t => t.table === ('sessoes' as string)));
    let altered = false;
    // Apenas teste unitário do comparador; isto NÃO simula homologação PostgreSQL real.
    const client = { async query(sql: string, params?: number[]) {
      const table = sql.match(/FROM "([a-z_]+)"/)![1];
      if (sql.includes('COUNT(*)')) return { rows: [{ count: String((db.prepare(`SELECT COUNT(*) AS n FROM "${table}"`).get() as { n: number }).n) }] };
      const query = sql.replace('$1', '?');
      const rows = db.prepare(query).all(...(params ?? [])) as Record<string, unknown>[];
      if (altered && table === 'itens' && rows.length) rows[0].estoque_atual = Number(rows[0].estoque_atual) + 1;
      return { rows };
    } } as unknown as PoolClient;
    assert.equal((await verifyTarget(client, expected)).length, migrationTables.length);
    altered = true;
    await assert.rejects(verifyTarget(client, expected), /Conteúdo divergente/);
  } finally { db.close(); }
});

test('Migração: guardas restringem host, porta e banco sem modificar instâncias existentes', () => {
  assert.ok(localMigrationUrl('postgresql://localhost:55432/brasilink_homologacao'));
  for (const url of ['postgresql://localhost:5432/brasilink_homologacao', 'postgresql://remote.example:55432/brasilink_homologacao', 'postgresql://localhost:55432/outro_banco', 'postgresql://localhost:55432/brasilink_homologacao?sslmode=disable', 'invalid']) {
    assert.throws(() => localMigrationUrl(url));
  }
});

test('Migração: schema inclui auditoria/FKs/identity e não contém sintaxe SQLite', async () => {
  const schema = await fs.readFile(new URL('../server/postgres-schema.sql', import.meta.url), 'utf8');
  for (const table of [...migrationTables, 'sessoes']) assert.ok(schema.includes(`CREATE TABLE ${table} (`));
  assert.ok(schema.includes('GENERATED BY DEFAULT AS IDENTITY'));
  assert.ok(schema.includes('DOUBLE PRECISION')); assert.ok(!schema.includes('AUTOINCREMENT'));
  assert.ok(schema.includes('REFERENCES separacao_itens(id)'));
});
